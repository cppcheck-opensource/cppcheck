class ResultIndex:
    """In-memory summaries of all result files, persisted as JSON sidecar files."""

    KINDS = ('results', 'info')

    def __init__(self, result_path: str, index_path: str) -> None:
        self.data_dirs = {'results': result_path, 'info': os.path.join(result_path, 'info_output')}
        self.sidecar_dirs = {kind: os.path.join(index_path, kind) for kind in self.KINDS}
        self.entries: Dict[str, Dict[str, Dict[str, Any]]] = {kind: {} for kind in self.KINDS}
        self.lock = threading.Lock()
        self.write_lock = threading.Lock()
        self.generation = 0
        self.ready = False

    def data_file(self, kind: str, package: str) -> str:
        return os.path.join(self.data_dirs[kind], package)

    def _sidecar_file(self, kind: str, package: str) -> str:
        return os.path.join(self.sidecar_dirs[kind], package + '.json')

    def _set(self, kind: str, package: str, entry: Optional[Dict[str, Any]]) -> None:
        with self.lock:
            if entry is None:
                if self.entries[kind].pop(package, None) is None:
                    return
            else:
                self.entries[kind][package] = entry
            self.generation += 1

    def snapshot(self, kind: str) -> Dict[str, Dict[str, Any]]:
        # entries are never modified in place, only replaced, so a shallow copy is enough
        with self.lock:
            return dict(self.entries[kind])

    def get(self, kind: str, package: str) -> Optional[Dict[str, Any]]:
        with self.lock:
            return self.entries[kind].get(package)

    def count(self, kind: str) -> int:
        with self.lock:
            return len(self.entries[kind])

    def _list_data_files(self, kind: str) -> Dict[str, List[int]]:
        path = self.data_dirs[kind]
        files = {}
        if not os.path.isdir(path):
            return files
        with os.scandir(path) as it:
            for de in it:
                if de.name.startswith('.') or de.name.endswith('.diff'):
                    continue
                try:
                    if not de.is_file():
                        continue
                    st = de.stat()
                except OSError:
                    continue
                files[de.name] = [st.st_mtime_ns, st.st_size]
        return files

    def _load_sidecar(self, kind: str, package: str, stamp: List[int]) -> Optional[Dict[str, Any]]:
        try:
            with open(self._sidecar_file(kind, package), 'rt', encoding='utf-8') as f:
                entry = json.load(f)
        except (OSError, ValueError):
            return None
        if entry.get('parser') != PARSER_VERSION or entry.get('stamp') != stamp:
            return None
        return entry

    def _parse_file(self, kind: str, package: str, text: Optional[str] = None) -> Dict[str, Any]:
        path = self.data_file(kind, package)
        st = os.stat(path)
        if text is None:
            text = read_text(path)
        entry = PARSERS[kind](text)
        # if the file is modified while it is read, the stamp does not match afterwards and
        # the file is parsed again by the next reconcile()
        entry['stamp'] = [st.st_mtime_ns, st.st_size]
        os.makedirs(self.sidecar_dirs[kind], exist_ok=True)
        write_atomic(self._sidecar_file(kind, package), json.dumps(entry))
        return entry

    def reconcile(self) -> None:
        """Bring the index in sync with the files on disk."""
        t_start = time.perf_counter()
        parsed = 0
        for kind in self.KINDS:
            files = self._list_data_files(kind)
            known = self.snapshot(kind)
            for package in known.keys() - files.keys():
                self._set(kind, package, None)
                try:
                    os.remove(self._sidecar_file(kind, package))
                except OSError:
                    pass
            for package, stamp in files.items():
                entry = known.get(package)
                if entry is not None and entry.get('stamp') == stamp:
                    continue
                entry = self._load_sidecar(kind, package, stamp)
                if entry is None:
                    try:
                        with self.write_lock:
                            entry = self._parse_file(kind, package)
                    except OSError as e:
                        logger.error('failed to index %s/%s: %s', kind, package, e)
                        continue
                    parsed += 1
                self._set(kind, package, entry)
        if not self.ready or parsed:
            logger.info('index reconciled in %.1fs (%d files parsed, %d results, %d info)',
                        time.perf_counter() - t_start, parsed, self.count('results'), self.count('info'))
        self.ready = True

    def store(self, kind: str, package: str, text: str) -> None:
        with self.write_lock:
            os.makedirs(self.data_dirs[kind], exist_ok=True)
            write_atomic(self.data_file(kind, package), text)
            entry = self._parse_file(kind, package, text)
        self._set(kind, package, entry)

    def remove(self, kind: str, package: str) -> None:
        with self.write_lock:
            for path in (self.data_file(kind, package), self._sidecar_file(kind, package)):
                if os.path.exists(path):
                    os.remove(path)
        self._set(kind, package, None)


