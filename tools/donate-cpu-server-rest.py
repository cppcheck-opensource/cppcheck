def _safe_package_name(package: str) -> str:
    if not package or package.startswith('.') or '/' in package or '\\' in package:
        raise HTTPException(status_code=404, detail='invalid package name')
    return package


async def _read_body(request: Request, limit: int) -> Tuple[str, bool]:
    """Returns the body (at most 'limit' bytes) and whether it was truncated."""
    chunks = []
    size = 0
    truncated = False
    async for chunk in request.stream():
        chunks.append(chunk)
        size += len(chunk)
        if size >= limit:
            truncated = True
            break
    data = b''.join(chunks)[:limit].decode('ascii', 'ignore')
    if data.endswith('\nDONE'):
        # sent by the socket based client
        data = data[:-len('\nDONE')]
    return data, truncated


def _upload_target(packages: PackageQueue, data: str) -> Tuple[str, str]:
    pos = data.find('\n')
    if pos == -1:
        raise HTTPException(status_code=400, detail='no newline found in data')
    if pos < 10:
        raise HTTPException(status_code=400, detail='first line is less than 10 characters')
    url = data[:pos].strip()
    res = RE_DEBIAN_URL.match(url) or RE_CPPCHECK_URL.match(url)
    if res is None:
        raise HTTPException(status_code=400, detail='unsupported package url')
    if not packages.contains(url):
        raise HTTPException(status_code=404, detail='url is not in packages')
    return url, res.group(1)


def _check_versions(data: str) -> None:
    for line in data.split('\n', 20)[:20]:
        if line.startswith('cppcheck: '):
            if OLD_VERSION not in line.split():
                raise HTTPException(status_code=422, detail='compared to wrong old version. Should be {}. Versions compared: {}'
                                    .format(OLD_VERSION, line[len('cppcheck: '):]))
            return
    raise HTTPException(status_code=422, detail='cppcheck versions missing in result data')


def _raw_suffix(request: Request, prefix: str) -> str:
    """The part of the undecoded path after 'prefix', decoded like donate-cpu-server.py does it
    ('+' is a space), so that links from the old server keep working."""
    raw = request.scope.get('raw_path') or request.url.path.encode()
    return urllib.parse.unquote_plus(raw.decode('latin-1')[len(prefix):])


def create_app(work_path: str, rescan_interval: float = DEFAULT_RESCAN_INTERVAL) -> FastAPI:
    result_path = os.path.join(work_path, 'donated-results')
    if not os.path.isdir(result_path):
        raise RuntimeError("result path '{}' is missing".format(result_path))

    packages = PackageQueue(work_path)
    index = ResultIndex(result_path, os.path.join(work_path, 'report-index'))
    cache = ReportCache(index, REPORT_MAX_AGE)

    def maintenance(stop: threading.Event) -> None:
        while True:
            try:
                index.reconcile()
            except Exception:
                logger.exception('index reconcile failed')
            if stop.wait(rescan_interval):
                return

    @asynccontextmanager
    async def lifespan(_app: FastAPI):
        stop = threading.Event()
        thread = threading.Thread(target=maintenance, args=(stop,), name='index', daemon=True)
        thread.start()
        yield
        stop.set()

    app = FastAPI(title='daca@home', version=SERVER_VERSION, lifespan=lifespan,
                  description='HTML reports, REST API and REST endpoints for donate-cpu.py clients.')

    def report(key: Any, compute: Callable[[], Dict[str, Any]]) -> Dict[str, Any]:
        def wrapped() -> Dict[str, Any]:
            return {'generated': datetime.datetime.now().isoformat(sep=' ', timespec='seconds'), **compute()}
        # 'complete' is false while the index is still being built after a start
        return {'complete': index.ready, **cache.get(key, wrapped)}

    def status_data() -> Dict[str, Any]:
        return {
            'server_version': SERVER_VERSION,
            'old_version': OLD_VERSION,
            'index_ready': index.ready,
            'results': index.count('results'),
            'info': index.count('info'),
            'packages': packages.count(),
        }

