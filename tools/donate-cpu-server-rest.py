_STACK_FRAME_PATTERNS = [
    # #0  0x00007ffff71cbf67 in raise () from /lib64/libc.so.6
    (re.compile(r'(?P<number>#\d+) .* in (?P<function>.+)\(.*\) from (?P<where>.*)$'), ' from '),
    # #11 0x00000000006f2414 in valueFlowNumber (tokenlist=tokenlist@entry=0x7fffffffc610) at build/valueflow.cpp:2503
    (re.compile(r'(?P<number>#\d+) .* in (?P<function>.+?) \(.*\) at (?P<where>.*)$'), ' at '),
    # #18 ForwardTraversal::updateRecursive (this=0x7fffffffb3c0, tok=0x14668a0) at build/forwardanalyzer.cpp:415
    (re.compile(r'(?P<number>#\d+) (?P<function>.+)\(.*\) at (?P<where>.*)$'), ' at '),
]


def _parse_stack_frame(line: str) -> Optional[str]:
    for pattern, sep in _STACK_FRAME_PATTERNS:
        m = pattern.search(line)
        if m:
            return m.group('number') + ' ' + m.group('function') + '(...)' + sep + m.group('where')
    return None


def _parse_crash(lines: List[str], i: int) -> Tuple[Dict[str, Any], int]:
    """lines[i] is the line after the ' received signal ' line."""
    crash_line = lines[i].strip() if i < len(lines) else ''
    i += 1
    code_line = ''
    if crash_line.rfind(' at ') > 0:
        code_line = lines[i].strip() if i < len(lines) else ''
        i += 1
    stack = []
    while i < len(lines):
        line = lines[i].rstrip()
        i += 1
        if not line.strip():
            break
        frame = _parse_stack_frame(line)
        if frame is None:
            break
        stack.append(frame)
    return {'crash_line': crash_line, 'code_line': code_line, 'stack_trace': stack}, i


def message_id_of(line: str) -> Optional[str]:
    """Message id of a warning line (same rules as the HEAD report of the old server)."""
    if not line.endswith(']'):
        return None
    if ': note: ' in line:
        # notes normally do not contain message ids but can end with ']'
        return None
    pos = line.rfind('[')
    if pos <= 0:
        return None
    message_id = line[pos + 1:-1]
    if not message_id or ' ' in message_id:
        return None
    return message_id


def extract_name(message_id: str, line: str) -> Optional[str]:
    """Function/type/variable/macro name that a checkLibrary*/unknownMacro/... message is about."""
    if message_id == 'unknownMacro':
        marker, end = 'required. If ', line.rfind('is a macro') - 1
    elif message_id == 'valueFlowBailoutIncompleteVar':
        marker, end = 'incomplete variable ', line.rfind('[') - 1
    elif message_id == 'checkLibraryFunction':
        marker, end = 'for function ', line.rfind('[') - 1
    elif message_id == 'checkLibraryCheckType':
        marker, end = 'configuration for ', line.rfind('[') - 1
    elif message_id in ('checkLibraryNoReturn', 'checkLibraryUseIgnore'):
        marker, end = ': Function ', line.rfind('should have') - 1
    else:
        return None
    start = line.find(marker)
    if start < 0 or end < 0:
        return None
    start += len(marker)
    if end <= start:
        return None
    return line[start:end]


def _header_value(line: str) -> str:
    parts = line.split(' ', 1)
    return parts[1] if len(parts) > 1 else ''


def _count_name(names: Dict[str, Dict[str, int]], message_id: str, line: str) -> None:
    name = extract_name(message_id, line)
    if name is not None:
        per_id = names.setdefault(message_id, {})
        per_id[name] = per_id.get(name, 0) + 1


def parse_result(text: str) -> Dict[str, Any]:
    lines = text.split('\n')
    entry: Dict[str, Any] = {
        'parser': PARSER_VERSION,
        'date': lines[0].strip(),
        'url': None,
        'versions': [],
        'count': [],
        'elapsed': [],
        'cppcheck_options': None,
        'platform': None,
        'python': None,
        'client_version': None,
        'compiler': None,
        'head_ids': {},   # message id -> number of warnings in head results
        'diff': {},       # message id -> [old count, head count]
        'names': {},      # message id -> {name: count}
        'crash': None,
    }
    head_names = {mid for mid, (kind, _) in NAME_REPORTS.items() if kind == 'results'}
    section = 'header'
    old_prefix = None
    i = 1
    while i < len(lines):
        line = lines[i].strip()
        i += 1
        if entry['crash'] is None and ' received signal ' in line:
            entry['crash'], i = _parse_crash(lines, i)
            continue
        if section == 'header':
            if entry['url'] is None and is_url(line):
                entry['url'] = line
            elif line.startswith('cppcheck: '):
                entry['versions'] = line.split()[1:]
                old = [v for v in entry['versions'] if v != 'head']
                if old:
                    old_prefix = old[0] + ' '
            elif line.startswith('count:'):
                entry['count'] = line.split()[1:]
            elif line.startswith('elapsed-time:'):
                try:
                    entry['elapsed'] = [float(v) for v in line.split()[1:]]
                except ValueError:
                    entry['elapsed'] = []
            elif line.startswith('cppcheck-options:'):
                entry['cppcheck_options'] = _header_value(line)
            elif line.startswith('platform:'):
                entry['platform'] = _header_value(line)
            elif line.startswith('python:'):
                entry['python'] = _header_value(line)
            elif line.startswith('client-version:'):
                entry['client_version'] = _header_value(line)
            elif line.startswith('compiler:'):
                entry['compiler'] = _header_value(line)
            elif line.startswith(HEAD_MARKER):
                section = 'head'
            elif line.startswith('diff:'):
                section = 'diff'
        elif section == 'head':
            if line.startswith('diff:'):
                section = 'diff'
                continue
            message_id = message_id_of(line)
            if message_id is None:
                continue
            entry['head_ids'][message_id] = entry['head_ids'].get(message_id, 0) + 1
            if message_id in head_names:
                _count_name(entry['names'], message_id, line)
        elif section == 'diff':
            if not line.endswith(']'):
                continue
            if old_prefix is not None and line.startswith(old_prefix):
                which = 0
            elif line.startswith('head '):
                which = 1
            else:
                continue
            message_id = line[line.rfind('[') + 1:-1]
            entry['diff'].setdefault(message_id, [0, 0])[which] += 1
    return entry


def parse_info(text: str) -> Dict[str, Any]:
    lines = text.split('\n')
    entry: Dict[str, Any] = {
        'parser': PARSER_VERSION,
        'date': lines[0].strip(),
        'url': None,
        'versions': [],
        'info_ids': {},
        'names': {},
    }
    info_names = {mid for mid, (kind, _) in NAME_REPORTS.items() if kind == 'info'}
    in_results = False
    for raw in lines[1:]:
        line = raw.strip()
        if not in_results:
            if entry['url'] is None and is_url(line):
                entry['url'] = line
            elif line.startswith('cppcheck: '):
                entry['versions'] = line.split()[1:]
            elif line.startswith(INFO_MARKER):
                in_results = True
            continue
        if line.startswith('diff:'):
            break
        message_id = message_id_of(line)
        if message_id is None:
            continue
        entry['info_ids'][message_id] = entry['info_ids'].get(message_id, 0) + 1
        if message_id in info_names:
            _count_name(entry['names'], message_id, line)
    return entry


PARSERS = {'results': parse_result, 'info': parse_info}


def read_text(path: str) -> str:
    with open(path, 'rt', encoding='utf-8', errors='replace') as f:
        return f.read()


def write_atomic(path: str, text: str) -> None:
    # the temporary file starts with '.' so that the glob() of donate-cpu-server.py ignores it
    directory, name = os.path.split(path)
    tmp = os.path.join(directory, '.' + name + '.tmp')
    with open(tmp, 'wt', encoding='utf-8') as f:
        f.write(text)
    os.replace(tmp, path)


