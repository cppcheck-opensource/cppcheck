    async def upload(request: Request, kind: str, limit: int) -> Dict[str, Any]:
        t_start = time.perf_counter()
        data, truncated = await _read_body(request, limit)
        url, package = _upload_target(packages, data)
        if kind == 'results':
            _check_versions(data)
        if truncated:
            logger.info('%s for %s is too large, removing result', kind, package)
            await run_in_threadpool(index.remove, kind, package)
            raise HTTPException(status_code=413, detail='data is too large (max {} bytes)'.format(limit))
        await run_in_threadpool(index.store, kind, package, str_date_time() + '\n' + data)
        logger.info('%s stored for %s (%d bytes / %.3fs)', kind, package, len(data), time.perf_counter() - t_start)
        return {'package': package, 'url': url, 'bytes': len(data)}

