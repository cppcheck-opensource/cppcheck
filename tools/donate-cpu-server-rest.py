class PackageQueue:
    """Hands out packages to REST clients.

    The package list is shared with donate-cpu-server.py, but the position in the list is kept in
    a separate file so that the two servers do not overwrite each other's state."""

    def __init__(self, work_path: str) -> None:
        self.index_file = os.path.join(work_path, 'package-index-rest.txt')
        self.nodata_file = os.path.join(work_path, 'packages_nodata.txt')
        self.lock = threading.Lock()

        with open(os.path.join(work_path, 'packages.txt'), 'rt') as f:
            packages: List[Optional[str]] = [val.strip() for val in f.readlines() if val.strip()]
        logger.info('packages: %d', len(packages))

        if os.path.isfile(self.nodata_file):
            # packages_nodata.txt is cleaned up by donate-cpu-server.py, so it is only read here
            with open(self.nodata_file, 'rt') as f:
                nodata = {val.strip() for val in f.readlines() if val.strip()}
            packages = [pkg for pkg in packages if pkg not in nodata]
            logger.info('packages (without packages with no files to process): %d', len(packages))

        if not packages:
            raise RuntimeError('there are no packages')

        self.packages = packages
        self.urls = set(packages)
        self.next_index = 0
        if os.path.isfile(self.index_file):
            try:
                with open(self.index_file, 'rt') as f:
                    self.next_index = int(f.read())
            except ValueError:
                pass
            if not 0 <= self.next_index < len(packages):
                self.next_index = 0

    def count(self) -> int:
        return len(self.packages)

    def contains(self, url: str) -> bool:
        with self.lock:
            return url in self.urls

    def get(self, index: int) -> Optional[str]:
        if 0 <= index < len(self.packages):
            return self.packages[index]
        return None

    def next(self) -> Optional[Tuple[int, str]]:
        with self.lock:
            for _ in range(len(self.packages)):
                index = self.next_index
                package = self.packages[index]
                self.next_index = (index + 1) % len(self.packages)
                if package is not None:
                    with open(self.index_file, 'wt') as f:
                        f.write(str(self.next_index) + '\n')
                    return index, package
        return None

    def mark_nodata(self, url: str) -> bool:
        with self.lock:
            if url not in self.urls:
                return False
            self.urls.discard(url)
            # keep the indexes stable
            self.packages = [None if pkg == url else pkg for pkg in self.packages]
            with open(self.nodata_file, 'at') as f:
                f.write(url + '\n')
        return True


class ReportCache:
    def __init__(self, index: ResultIndex, max_age: float) -> None:
        self.index = index
        self.max_age = max_age
        self.lock = threading.Lock()
        self.cache: Dict[Any, Tuple[int, float, Any]] = {}

    def get(self, key: Any, compute: Callable[[], Any]) -> Any:
        generation = self.index.generation
        with self.lock:
            hit = self.cache.get(key)
        if hit is not None and (hit[0] == generation or time.monotonic() - hit[1] < self.max_age):
            return hit[2]
        value = compute()
        with self.lock:
            if len(self.cache) > 1000:
                self.cache.clear()
            self.cache[key] = (generation, time.monotonic(), value)
        return value


