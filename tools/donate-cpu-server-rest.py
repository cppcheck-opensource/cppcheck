def is_current(entry: Dict[str, Any]) -> bool:
    """Result was compared against the current OLD_VERSION."""
    return OLD_VERSION in entry.get('versions', [])


def by_version(entry: Dict[str, Any], values: List[Any]) -> Tuple[Any, Any]:
    """(head value, old value) of a 'count:'/'elapsed-time:' list."""
    versions = entry.get('versions', [])
    if len(values) < 2:
        return None, None
    head_i = versions.index('head') if 'head' in versions else 0
    old_i = versions.index(OLD_VERSION) if OLD_VERSION in versions else 1 - head_i
    if max(head_i, old_i) >= len(values):
        return None, None
    return values[head_i], values[old_i]


def package_row(package: str, entry: Dict[str, Any]) -> Dict[str, Any]:
    return {'package': package, 'date': entry.get('date'), 'url': entry.get('url')}


def crash_report(entries: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    rows = []
    stack_traces: Dict[str, Dict[str, Any]] = {}
    for package in sorted(entries):
        entry = entries[package]
        if not is_current(entry):
            continue
        head, old = by_version(entry, entry.get('count', []))
        head_crash, old_crash = head == 'Crash!', old == 'Crash!'
        if not head_crash and not old_crash:
            continue
        rows.append(dict(package_row(package, entry), head_crash=head_crash, old_crash=old_crash))
        crash = entry.get('crash')
        if head_crash and crash:
            key = '\n'.join(crash['stack_trace'])
            group = stack_traces.get(key)
            if group is None:
                stack_traces[key] = dict(crash, packages=[package])
            else:
                group['packages'].append(package)
    groups = sorted(stack_traces.values(), key=lambda g: len(g['packages']), reverse=True)
    return {'old_version': OLD_VERSION, 'packages': rows, 'stack_traces': groups}


def timeout_report(entries: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    rows = []
    for package in sorted(entries):
        entry = entries[package]
        if not is_current(entry):
            continue
        head, old = by_version(entry, entry.get('count', []))
        if head == 'TO!' or old == 'TO!':
            rows.append(dict(package_row(package, entry), head_timeout=head == 'TO!', old_timeout=old == 'TO!'))
    return {'old_version': OLD_VERSION, 'packages': rows}


def stale_report(entries: Dict[str, Dict[str, Any]], days: int) -> Dict[str, Any]:
    now = datetime.datetime.now()
    rows = []
    for package in sorted(entries):
        entry = entries[package]
        try:
            age = (now - date_time_from_str(entry.get('date', ''))).days
        except ValueError:
            # there might be very outdated files which still might have an invalid timestamp
            age = None
        if age is None or age >= days:
            rows.append(dict(package_row(package, entry), age_days=age))
    return {'days': days, 'packages': rows}


def _sum_counts(per_package: List[Dict[str, Any]], width: int) -> Dict[str, List[int]]:
    counts: Dict[str, List[int]] = {}
    for item in per_package:
        for message_id, value in item.items():
            values = value if isinstance(value, list) else [value]
            total = counts.setdefault(message_id, [0] * width)
            for n, v in enumerate(values):
                total[n] += v
    return dict(sorted(counts.items()))


def diff_report(entries: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    today = today_str()
    current = [e for e in entries.values() if is_current(e)]

    def to_json(counts: Dict[str, List[int]]) -> Dict[str, Any]:
        return {
            'message_ids': {mid: {'old': c[0], 'head': c[1]} for mid, c in counts.items()},
            'total': {'old': sum(c[0] for c in counts.values()), 'head': sum(c[1] for c in counts.values())},
        }

    return {
        'old_version': OLD_VERSION,
        'today': to_json(_sum_counts([e['diff'] for e in current if e['date'].startswith(today)], 2)),
        'all': to_json(_sum_counts([e['diff'] for e in current], 2)),
    }


def summary_report(entries: Dict[str, Dict[str, Any]], ids_key: str) -> Dict[str, Any]:
    today = today_str()
    current = [e for e in entries.values() if is_current(e)]

    def to_json(counts: Dict[str, List[int]]) -> Dict[str, Any]:
        return {'message_ids': {mid: c[0] for mid, c in counts.items()},
                'total': sum(c[0] for c in counts.values())}

    return {
        'today': to_json(_sum_counts([e[ids_key] for e in current if e['date'].startswith(today)], 1)),
        'all': to_json(_sum_counts([e[ids_key] for e in current], 1)),
    }


def latest_report(entries: Dict[str, Dict[str, Any]], limit: int = MAX_LATEST) -> Dict[str, Any]:
    newest = sorted(entries.items(), key=lambda kv: kv[1].get('stamp', [0])[0], reverse=True)[:limit]
    rows = []
    for package, entry in newest:
        head, old = by_version(entry, entry.get('count', []))
        lost = sum(c[0] for c in entry['diff'].values())
        added = sum(c[1] for c in entry['diff'].values())
        rows.append(dict(package_row(package, entry), head_count=head, old_count=old, lost=lost, added=added))
    return {'old_version': OLD_VERSION, 'packages': rows}


def time_report(entries: Dict[str, Dict[str, Any]], regressed: bool, factor: float) -> Dict[str, Any]:
    threshold = factor if regressed else 1.0 / factor
    rows = []
    total_old = 0.0
    total_head = 0.0
    for package, entry in entries.items():
        if not is_current(entry):
            continue
        head, old = by_version(entry, entry.get('elapsed', []))
        if head is None or old is None:
            continue
        if old < 0.0 or head < 0.0:
            # ignore results with crashes / errors for the time report
            continue
        if old == 0.0 and head == 0.0:
            continue
        total_old += old
        total_head += head
        if old == head:
            continue
        if old > 0.0 and head > 0.0:
            time_factor = head / old
        elif old == 0.0:
            # the smallest possible value is 0.1 so treat that as an increase of 100%
            # on top of the existing 100% (treating the base 0.0 as such).
            time_factor = 1.0 + (head * 10)
        else:
            time_factor = 0.0
        if (regressed and time_factor > threshold) or (not regressed and time_factor < threshold):
            rows.append(dict(package_row(package, entry), old_time=old, head_time=head, factor=round(time_factor, 2)))
    rows.sort(key=lambda r: r['factor'], reverse=regressed)
    return {
        'old_version': OLD_VERSION,
        'direction': 'regressed' if regressed else 'improved',
        'threshold': round(threshold, 2),
        'packages': rows,
        'total': {'old_time': round(total_old, 1), 'head_time': round(total_head, 1),
                  'factor': round(total_head / total_old, 2) if total_old > 0.0 else 0.0},
    }


def slowest_report(entries: Dict[str, Dict[str, Any]], limit: int) -> Dict[str, Any]:
    rows = []
    for package, entry in entries.items():
        if not is_current(entry):
            continue
        head_count, _ = by_version(entry, entry.get('count', []))
        if head_count == 'TO!':
            continue
        head, old = by_version(entry, entry.get('elapsed', []))
        if head is None or old is None or head < 0.0 or old < 0.0:
            continue
        rows.append(dict(package_row(package, entry), old_time=old, head_time=head))
    rows.sort(key=lambda r: r['head_time'], reverse=True)
    return {'old_version': OLD_VERSION, 'packages': rows[:limit]}


def names_report(entries: Dict[str, Dict[str, Any]], message_id: str, limit: int) -> Dict[str, Any]:
    counts: Dict[str, int] = {}
    for entry in entries.values():
        if not is_current(entry):
            continue
        for name, n in entry['names'].get(message_id, {}).items():
            counts[name] = counts.get(name, 0) + n
    items = sorted(counts.items(), key=lambda kv: kv[1], reverse=True)
    return {
        'message_id': message_id,
        'item': NAME_REPORTS[message_id][1],
        'total_names': len(items),
        'names': [{'name': name, 'count': n} for name, n in items[:limit]],
    }


def clients_report(entries: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    keys = ('client_version', 'python', 'platform', 'compiler')
    out: Dict[str, Dict[str, Dict[str, Any]]] = {k: {} for k in keys}
    for entry in entries.values():
        if not is_current(entry):
            continue
        date = entry.get('date', '')
        for k in keys:
            value = entry.get(k)
            if not value:
                continue
            item = out[k].setdefault(value, {'packages': 0, 'first_seen': date, 'last_seen': date})
            item['packages'] += 1
            item['first_seen'] = min(item['first_seen'], date)
            item['last_seen'] = max(item['last_seen'], date)
    return {k: dict(sorted(v.items())) for k, v in out.items()}


# Listings of the actual warning lines. These read the result files, but only those that the
# index says contain the message id.

def _scan_file(path: str, start: Callable[[str], bool], stop: Optional[str],
               match: Callable[[str], bool]) -> Tuple[Optional[str], Optional[str], List[str]]:
    url = None
    options = None
    lines = []
    in_section = False
    with open(path, 'rt', encoding='utf-8', errors='replace') as f:
        for line in f:
            line = line.rstrip('\n')
            if not in_section:
                if url is None and is_url(line):
                    url = line
                elif line.startswith('cppcheck-options:'):
                    options = _header_value(line)
                if start(line):
                    in_section = True
                continue
            if stop is not None and line.startswith(stop):
                break
            if match(line):
                lines.append(line)
    return url, options, lines


def listing(index: ResultIndex, kind: str, packages: List[str], start: Callable[[str], bool],
            stop: Optional[str], match: Callable[[str], bool]) -> List[Dict[str, Any]]:
    out = []
    for package in sorted(packages):
        try:
            url, options, lines = _scan_file(index.data_file(kind, package), start, stop, match)
        except OSError:
            continue
        if lines:
            out.append({'package': package, 'url': url, 'cppcheck_options': options, 'lines': lines})
    return out


