def main() -> None:
    parser = argparse.ArgumentParser(description='daca@home HTTP server (HTML reports and REST API)')
    parser.add_argument('--test', action='store_true', help='use port 8080 (unless --port is given)')
    parser.add_argument('--host', default='0.0.0.0')
    parser.add_argument('--port', type=int, help='default: 80')
    parser.add_argument('--work-path', help='default: /var/daca@home or ~/daca@home')
    parser.add_argument('--rescan-interval', type=float, default=DEFAULT_RESCAN_INTERVAL,
                        help='seconds between checks for result files written by donate-cpu-server.py (default: %(default)s)')
    args = parser.parse_args()

    logging.basicConfig(level=logging.INFO, format='[%(asctime)s] %(message)s')

    work_path = args.work_path
    if work_path is None:
        work_path = '/var/daca@home'
        if not os.path.isdir(work_path):
            work_path = os.path.expanduser('~/daca@home')
    work_path = os.path.abspath(work_path)
    logger.info('version %s, work path: %s', SERVER_VERSION, work_path)

    try:
        app = create_app(work_path, args.rescan_interval)
    except (RuntimeError, OSError) as e:
        logger.error('fatal: %s', e)
        sys.exit(1)

    port = args.port if args.port is not None else (8080 if args.test else 80)
    uvicorn.run(app, host=args.host, port=port)


if __name__ == '__main__':
    main()
