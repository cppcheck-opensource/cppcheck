#!/usr/bin/env python3

# HTTP server for daca@home: HTML reports, a REST API and REST endpoints for 'donate-cpu.py'.
#
# This server can run side by side with donate-cpu-server.py:
#  - donate-cpu-server.py keeps serving the old socket protocol (port 8000) for old clients and
#    writes the result files into <work path>/donated-results.
#  - This server (port 80 by default) serves the reports. It picks up result files written by
#    donate-cpu-server.py by checking the result directories regularly. It also accepts uploads
#    from clients using the REST API.
# The URLs of the HTML reports are the same as those of donate-cpu-server.py.
#
# Reports are NOT generated by reading all result files on each request. Every result file is
# parsed once when it is stored or detected, and a compact summary of it (counts, timings, crash
# stack, message id counts, diff sums, ...) is kept in memory. The summary is also persisted as a
# JSON "sidecar" file in <work path>/report-index so that a restart does not need to parse all
# results again. All reports are computed from these summaries and cached.
# Pages that list the actual warning lines for a message id read only the result files that the
# index says contain that message id, and those listings are cached as well.
#
# Requirements: see donate-cpu-server-requirements.txt
# Usage: donate-cpu-server-rest.py [--test] [--host HOST] [--port PORT] [--work-path PATH]
# The REST API documentation is available at /docs when the server is running.

